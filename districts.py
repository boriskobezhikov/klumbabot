"""
Канонический список районов Тбилиси.

Нужен, чтобы «Ваке», "Vake" и «ვაკე» считались одним и тем же районом. Это
основа фильтра по районам: у ss.ge район приходит структурно по-грузински, из
чата — свободным текстом на русском, и оба надо привести к одному значению.

Список курируемый, а не полный: у ss.ge 51 подрайон, но в кнопках нужны те,
которыми люди реально мыслят при поиске жилья. Всё, что не опознано, попадает
в None — такие объявления проходят фильтр по району всегда, чтобы редкое
место не потерялось молча.
"""

